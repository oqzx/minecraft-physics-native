// Which releases run each ungated function (B280): generated/shared-reach.json. An ungated function serves every release
// from one body, so a cited method that changes at a boundary matters to it only if releases on both sides run it. This
// records which do, from the Rust tests and from a replay of the pinned corpus of every release.
//
//   node scripts/reach-probe.cjs prepare <dir>              the gate-mutants copy of native/ in <dir>, every ungated function
//                                                          noting that it ran, and on which release
//   node scripts/reach-probe.cjs tests <dir> <test binary>  the Rust tests of that copy: <dir>/reach-tests.tsv
//   node scripts/reach-corpus.cjs <dir> <release...>        in the recorder package (@minecraft-physics-native/recorder,
//                                                          not this repository): the corpus of each release replayed
//                                                          on the copy's addon (its replay/gate-sweep.ts, no mutant,
//                                                          --wide): <dir>/reach-<release>.tsv
//   node scripts/reach-probe.cjs collect <dir>              writes generated/shared-reach.json
//
// The copy's gate probe (scripts/gate-mutants.cjs) knows the release of every gate it answers. A function's hit is put down
// to the release of the corpus a process replays (REACH_RELEASE), or in a Rust test to every release whose gates that test's
// thread ran: a test of two releases counts both for each function it ran, which says a function runs on more releases than
// it may, never fewer. A test that ran no gate counts for every release. A function the copy cannot note (a `const fn`,
// which may be called in a const context, or a declaration with no body) is listed under `unprobed`, and is taken as
// reached everywhere.
//
// Reach is what these runs did, not what a release can do: a release no test or recording takes into a function is
// `unreached` there, and a boundary is crossed only by a function reached on both sides of it. The generator
// (scripts/shared-equivalence.cjs) uses it so, and says so in each function's entry.
const childProcess = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const { sharedFunctions } = require("./shared-functions.cjs");
const { canonicalReleases } = require("./release-inventory.cjs");

const root = path.resolve(__dirname, "..");
const outputPath = path.join(root, "generated", "shared-reach.json");

const PROBE = (count) => `// generated by scripts/reach-probe.cjs, in the probe copy only
use std::cell::{Cell, RefCell};
use std::collections::HashSet;
use std::io::Write;
use std::sync::{Mutex, OnceLock};

pub const FUNCTIONS: usize = ${count};
static LOG: OnceLock<Option<(Mutex<std::fs::File>, Option<String>)>> = OnceLock::new();
thread_local! {
    static RELEASE: Cell<u64> = const { Cell::new(0) };
    static SEEN: RefCell<HashSet<(u8, u32, u64)>> = RefCell::new(HashSet::new());
}

fn from_env() -> Option<(Mutex<std::fs::File>, Option<String>)> {
    let path = std::env::var("REACH_HITS").ok()?;
    let file = std::fs::OpenOptions::new().create(true).append(true).open(path).ok()?;
    Some((Mutex::new(file), std::env::var("REACH_RELEASE").ok()))
}

fn unpack(release: u64) -> String {
    if release == 0 {
        "?".to_string()
    } else {
        let (major, minor, patch) = (release >> 32, (release >> 16) & 0xffff, release & 0xffff);
        if patch == 0 { format!("{major}.{minor}") } else { format!("{major}.{minor}.{patch}") }
    }
}

fn note(kind: u8, id: u32, release: u64) {
    let Some((log, fixed)) = LOG.get_or_init(from_env) else { return };
    if !SEEN.with(|seen| seen.borrow_mut().insert((kind, id, release))) {
        return;
    }
    let thread = std::thread::current();
    let name = thread.name().unwrap_or("?");
    let shown = fixed.clone().unwrap_or_else(|| unpack(release));
    let tag = if kind == 0 { "F" } else { "G" };
    let _ = writeln!(log.lock().unwrap(), "{tag}\\t{id}\\t{shown}\\t{name}");
}

/// A gate of this release ran on this thread (called by the gate probe).
pub fn release(packed: u64) {
    RELEASE.with(|current| current.set(packed));
    note(1, 0, packed);
}

/// Ungated function \`id\` ran.
#[inline]
pub fn hit(id: u32) {
    note(0, id, RELEASE.with(Cell::get));
}
`;

/** The opening brace of the body of the function declared at `line` (1-based), or -1 for a declaration with no body. */
function bodyOpening(text, line) {
  let at = 0;
  for (let index = 1; index < line; index += 1) at = text.indexOf("\n", at) + 1;
  const start = text.indexOf("fn ", at);
  let depth = 0;
  for (let index = start; index < text.length; index += 1) {
    const ch = text[index];
    if (ch === "(" || ch === "[") depth += 1;
    else if (ch === ")" || ch === "]") depth -= 1;
    else if (depth === 0 && ch === ";") return -1;
    else if (depth === 0 && ch === "{") return index;
  }
  return -1;
}

/** The functions the probe notes, numbered: those scripts/shared-equivalence.cjs makes claims of. */
function probedFunctions() {
  const { ungatedFunctions } = require("./shared-equivalence.cjs");
  const wanted = new Set(ungatedFunctions().map(({ file, function: name }) => `${file}:${name}`));
  const ids = new Map();
  const declarations = [];
  for (const entry of sharedFunctions()) {
    const key = `${entry.file}:${entry.function}`;
    if (!wanted.has(key)) continue;
    if (!ids.has(key)) ids.set(key, ids.size);
    declarations.push({ key, file: entry.file, line: entry.line, id: ids.get(key) });
  }
  return { ids, declarations };
}

function prepare(target) {
  require("./gate-mutants.cjs").prepare(target);
  const copied = path.join(target, "native", "src");
  const { ids, declarations } = probedFunctions();
  const unprobed = [];
  const byFile = new Map();
  for (const declaration of declarations) byFile.set(declaration.file, [...(byFile.get(declaration.file) ?? []), declaration]);
  for (const [file, declared] of byFile) {
    const at = path.join(copied, file);
    let text = fs.readFileSync(at, "utf8").replace(/\r\n/g, "\n");
    // sharedFunctions numbers a declaration among the code lines (codeLines leaves the cfg(test) items out), so each is
    // mapped back to its line in the file before anything is inserted
    const sourceLines = [...require("./shared-gates.cjs").codeLineNumbers(text)].sort((left, right) => left - right);
    const held = declared.map((declaration) => ({ ...declaration, line: sourceLines[declaration.line - 1] + 1 }));
    // from the bottom up, so that an insertion moves no line still to come; a line moved by the gate rewrite is not
    // (gate-mutants rewrites within a line)
    for (const declaration of held.toSorted((left, right) => right.line - left.line)) {
      const lineStart = text.split("\n").slice(0, declaration.line - 1).join("\n").length + (declaration.line > 1 ? 1 : 0);
      const lineEnd = text.indexOf("\n", lineStart);
      const head = text.slice(lineStart, lineEnd);
      const opening = bodyOpening(text, declaration.line);
      if (opening < 0 || /\bconst\s+fn\b/.test(text.slice(lineStart, opening)) || /\bconst\s+fn\b/.test(head)) {
        unprobed.push(declaration.key);
        continue;
      }
      text = `${text.slice(0, opening + 1)} crate::reach_probe::hit(${declaration.id});${text.slice(opening + 1)}`;
    }
    fs.writeFileSync(at, text);
  }
  const gateProbe = path.join(copied, "gate_probe.rs");
  const probe = fs.readFileSync(gateProbe, "utf8");
  const anchor = "    let version = held.released();\n";
  if (!probe.includes(anchor)) throw new Error("the gate probe changed: no release to hand on");
  fs.writeFileSync(gateProbe, probe.replace(anchor, `${anchor}    crate::reach_probe::release(pack(version));\n`));
  fs.writeFileSync(path.join(copied, "reach_probe.rs"), PROBE(ids.size));
  const lib = path.join(copied, "lib.rs");
  fs.writeFileSync(lib, `pub mod reach_probe;\n${fs.readFileSync(lib, "utf8")}`);
  fs.writeFileSync(path.join(target, "reach-functions.json"), `${JSON.stringify({ functions: [...ids.keys()], unprobed: [...new Set(unprobed)].sort() }, null, 1)}\n`);
  console.log(`${ids.size - new Set(unprobed).size} of ${ids.size} functions probed, in ${target}`);
}


function tests(target, binary) {
  const out = path.join(target, "reach-tests.tsv");
  fs.writeFileSync(out, "");
  const run = childProcess.spawnSync(binary, ["--test-threads", "4"], { cwd: path.join(target, "native"), env: { ...process.env, REACH_HITS: out }, encoding: "utf8", maxBuffer: 1 << 28 });
  console.log(run.stdout.trim().split("\n").at(-1));
  if (run.status !== 0) throw new Error(run.stdout.slice(-3000));
}

/** Releases as ranges of the registered list: ["1.8.8..1.12.2", "1.21.2"]. */
function ranges(releases, registered) {
  const held = new Set(releases);
  const out = [];
  let from = null;
  registered.forEach((release, index) => {
    if (held.has(release) && from === null) from = release;
    if (from !== null && (!held.has(registered[index + 1]) || index === registered.length - 1)) {
      out.push(from === release ? release : `${from}..${release}`);
      from = null;
    }
  });
  return out;
}

/** The releases a list of ranges holds. */
function expand(list, registered) {
  const out = new Set();
  for (const item of list) {
    const [from, to] = item.split("..");
    const first = registered.indexOf(from);
    const last = registered.indexOf(to ?? from);
    if (first < 0 || last < first) throw new Error(`not a range of registered releases: ${item}`);
    for (let index = first; index <= last; index += 1) out.add(registered[index]);
  }
  return out;
}

/** How many of the Rust tests that ran a function its entry names. */
const RAN_BY = 12;

function collect(target) {
  const registered = canonicalReleases();
  const { functions, unprobed } = JSON.parse(fs.readFileSync(path.join(target, "reach-functions.json"), "utf8"));
  const reach = new Map(functions.map((key) => [key, { tests: new Set(), corpus: new Set(), names: new Set() }]));
  const read = (file) => fs.readFileSync(file, "utf8").split("\n").filter(Boolean).map((line) => line.split("\t"));
  // the Rust tests: each test thread's gate releases, then its function hits put down to them
  const gatesOf = new Map();
  const lines = read(path.join(target, "reach-tests.tsv"));
  for (const [tag, , release, test] of lines) {
    if (tag === "G" && release !== "?") gatesOf.set(test, (gatesOf.get(test) ?? new Set()).add(release));
  }
  for (const [tag, id, , test] of lines) {
    if (tag !== "F") continue;
    const releases = gatesOf.get(test);
    if (test !== "main" && test !== "?") reach.get(functions[Number(id)]).names.add(test.replace(/^.*::/, ""));
    for (const release of releases && test !== "main" && test !== "?" ? releases : registered) reach.get(functions[Number(id)]).tests.add(release);
  }
  const replayed = [];
  for (const release of registered) {
    const file = path.join(target, `reach-${release}.tsv`);
    if (!fs.existsSync(`${file}.done`)) continue;
    replayed.push(release);
    for (const [tag, id, at] of read(file)) if (tag === "F") reach.get(functions[Number(id)]).corpus.add(at);
  }
  const missing = registered.filter((release) => !replayed.includes(release));
  if (missing.length > 0) throw new Error(`no finished corpus replay of ${missing.join(", ")}`);
  const entries = [...reach].map(([key, { tests: byTests, corpus: byCorpus, names }]) => {
    const [file, name] = key.split(":");
    if (unprobed.includes(key)) return { file, function: name, unprobed: true, reached: ranges(registered, registered) };
    const all = new Set([...byTests, ...byCorpus]);
    // (some of the Rust tests that ran it, by name, for a helper's review to name: scripts/shared-equivalence.cjs helperProblems)
    const ranBy = [...names].sort().slice(0, RAN_BY);
    return { file, function: name, reached: ranges([...all], registered), tests: ranges([...byTests], registered), corpus: ranges([...byCorpus], registered), ranBy };
  }).sort((left, right) => `${left.file}:${left.function}`.localeCompare(`${right.file}:${right.function}`));
  const commit = childProcess.execFileSync("git", ["-C", root, "rev-parse", "--short=8", "HEAD"], { encoding: "utf8" }).trim();
  const document = { schema: 1, generatedBy: "scripts/reach-probe.cjs", probedAt: commit, corpus: "the recorder package's corpus/ (every release, --wide)", functions: entries };
  fs.writeFileSync(outputPath, `${JSON.stringify(document, null, 1)}\n`);
  const counts = { functions: entries.length, everywhere: entries.filter((entry) => entry.reached.length === 1 && entry.reached[0] === `${registered[0]}..${registered.at(-1)}`).length, never: entries.filter((entry) => entry.reached.length === 0).length };
  console.log(JSON.stringify(counts));
}

/** The record of reach, when there is one: `file:function` to the set of releases that ran it. */
function readReach() {
  if (!fs.existsSync(outputPath)) return null;
  const registered = canonicalReleases();
  const document = JSON.parse(fs.readFileSync(outputPath, "utf8"));
  return { probedAt: document.probedAt, byFunction: new Map(document.functions.map((entry) => [`${entry.file}:${entry.function}`, { releases: expand(entry.reached, registered), unprobed: Boolean(entry.unprobed), ranBy: new Set(entry.ranBy ?? []) }])) };
}

if (require.main === module) {
  const [command, target, ...rest] = process.argv.slice(2);
  if (command === "prepare" && target) prepare(path.resolve(target));
  else if (command === "tests" && target) tests(path.resolve(target), rest[0]);
  else if (command === "collect" && target) collect(path.resolve(target));
  else {
    console.error("usage: reach-probe.cjs prepare|tests|collect <dir> ... (the corpus step is the recorder package's scripts/reach-corpus.cjs)");
    process.exit(1);
  }
}

module.exports = { readReach, ranges, expand, outputPath, bodyOpening };
