// A mutation build of the engine, for what no number of matching replays says: whether anything would fail were a version
// gate wrong (docs/validation-records.md: a gate moved a whole release passed 41 replays).
//
//   node scripts/gate-mutants.cjs prepare <dir>    copies native/ to <dir>, every gate outside tests taking a site number
//   node scripts/gate-mutants.cjs sites            prints the sites, one JSON line each
//   node scripts/gate-mutants.cjs unit <dir> <test binary> <jobs>   each gate flipped on each release beside its boundary,
//                                                  against the Rust tests that run that gate on that release
//   node scripts/gate-mutants.cjs js <dir> <jobs>  what unit left, against the test/*.test.cjs files that run that gate there
//   node scripts/gate-mutants.cjs recheck <dir> <test binary> <out.jsonl> <test filter> <site>[,<site>...]
//                                                  chosen gates flipped again on both sides against the Rust tests the filter
//                                                  names, for fixtures added since a sweep; gate-report reads <out> as unit.jsonl
//
// The copy is what is built, never the checkout. `release.at_least(1, 21, 5)` there reads
// `crate::gate_probe::gate(release, 17, release.at_least(1, 21, 5))`, and gate_probe.rs notes that the site ran and can flip
// its answer for one release alone. So one build holds every mutant, and flipping a gate on the release either side of its
// boundary is the gate moved one release that way: a failure on that release is that gate's.
const fs = require("node:fs");
const path = require("node:path");
const { codeLineNumbers } = require("./shared-gates.cjs");
const { canonicalReleases } = require("./release-inventory.cjs");
const { compareReleases } = require("./registered-releases.cjs");

const root = path.resolve(__dirname, "..");
const sourceRoot = path.join(root, "native", "src");
const GATE = /([A-Za-z_][\w.]*(?:\(\))?)\.at_least\((\d+),\s*(\d+),\s*(\d+)\)/g;

const rustFiles = (base = sourceRoot) => {
  const found = [];
  const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const file = path.join(directory, entry.name);
      if (entry.isDirectory()) walk(file);
      else if (entry.name.endsWith(".rs")) found.push(file);
    }
  };
  walk(base);
  return found.sort();
};

/** Every gate outside the tests, numbered in file and line order (of native/src, or of another copy of it). */
function gateSites(registered = canonicalReleases(), base = sourceRoot) {
  const sites = [];
  for (const file of rustFiles(base)) {
    if (/tests\.rs$/.test(file)) continue;
    const text = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    const code = codeLineNumbers(text);
    let current = "<module>";
    text.split("\n").forEach((line, index) => {
      const declared = /^\s*(?:pub(?:\([a-z]+\))? )?(?:const )?fn (\w+)/.exec(line);
      if (declared) current = declared[1];
      if (!code.has(index)) return;
      for (const match of line.matchAll(GATE)) {
        if (/fn at_least/.test(line)) continue;
        const [, , major, minor, patch] = match;
        const boundary = patch === "0" ? `${major}.${minor}` : `${major}.${minor}.${patch}`;
        const from = registered.findIndex((release) => compareReleases(release, boundary) >= 0);
        sites.push({
          site: sites.length,
          file: path.relative(base, file).replaceAll(path.sep, "/"),
          line: index + 1,
          function: current,
          boundary,
          firstFrom: from < 0 ? null : registered[from],
          lastBefore: from > 0 ? registered[from - 1] : null,
          text: line.trim(),
        });
      }
    });
  }
  return sites;
}

const PROBE = (count) => `// generated by scripts/gate-mutants.cjs, in the mutation copy only
use crate::version::MinecraftVersion;
use std::collections::HashSet;
use std::io::Write;
use std::sync::atomic::{AtomicBool, AtomicU32, AtomicU64, Ordering::Relaxed};
use std::sync::{Mutex, OnceLock};

pub const SITES: usize = ${count};
#[allow(clippy::declare_interior_mutable_const)]
const CLEAR: AtomicBool = AtomicBool::new(false);
static HITS: [AtomicBool; SITES] = [CLEAR; SITES];
static MUTANT_SITE: AtomicU32 = AtomicU32::new(u32::MAX);
static MUTANT_RELEASE: AtomicU64 = AtomicU64::new(0);
static LOG: OnceLock<Option<Mutex<std::fs::File>>> = OnceLock::new();
thread_local! { static SEEN: std::cell::RefCell<HashSet<(u32, u64)>> = std::cell::RefCell::new(HashSet::new()); }

const fn pack(version: MinecraftVersion) -> u64 {
    ((version.major as u64) << 32) | ((version.minor as u64) << 16) | version.patch as u64
}

fn from_env() -> Option<Mutex<std::fs::File>> {
    if let Ok(mutant) = std::env::var("GATE_MUTANT") {
        if let Some((site, release)) = mutant.split_once(':') {
            if let (Ok(site), Some(release)) = (site.parse(), MinecraftVersion::parse(release)) {
                set(site, pack(release));
            }
        }
    }
    let path = std::env::var("GATE_HITS").ok()?;
    Some(Mutex::new(std::fs::OpenOptions::new().create(true).append(true).open(path).ok()?))
}

fn set(site: u32, release: u64) {
    MUTANT_RELEASE.store(release, Relaxed);
    MUTANT_SITE.store(site, Relaxed);
}

/// What holds a release: the release, or a scene that has one.
pub trait Released {
    fn released(&self) -> MinecraftVersion;
}
impl Released for MinecraftVersion {
    fn released(&self) -> MinecraftVersion {
        *self
    }
}
impl<T: Released> Released for &mut T {
    fn released(&self) -> MinecraftVersion {
        (**self).released()
    }
}
impl<T: Released> Released for &T {
    fn released(&self) -> MinecraftVersion {
        (**self).released()
    }
}

/// The gate's answer, flipped when this site is the mutant on this release.
#[inline]
pub fn gate(held: impl Released, site: u32, real: bool) -> bool {
    let version = held.released();
    let log = LOG.get_or_init(from_env);
    if !HITS[site as usize].load(Relaxed) {
        HITS[site as usize].store(true, Relaxed);
    }
    let release = pack(version);
    if let Some(log) = log {
        let fresh = SEEN.with(|seen| seen.borrow_mut().insert((site, release)));
        if fresh {
            let thread = std::thread::current();
            let name = thread.name().unwrap_or("?");
            let _ = writeln!(log.lock().unwrap(), "{site}\\t{version}\\t{name}");
        }
    }
    if MUTANT_SITE.load(Relaxed) == site && MUTANT_RELEASE.load(Relaxed) == release {
        !real
    } else {
        real
    }
}

/// The sites that ran since the last call.
#[must_use]
pub fn drain() -> Vec<u32> {
    let mut sites = Vec::new();
    for (site, hit) in HITS.iter().enumerate() {
        if hit.swap(false, Relaxed) {
            sites.push(site as u32);
        }
    }
    sites
}

#[cfg(feature = "bindings")]
#[napi_derive::napi]
pub fn gate_probe_drain() -> Vec<u32> {
    drain()
}

/// Makes \`site\` the mutant on \`release\`; a negative site clears it.
#[cfg(feature = "bindings")]
#[napi_derive::napi]
pub fn gate_probe_set(site: i32, release: String) {
    match (u32::try_from(site), MinecraftVersion::parse(&release)) {
        (Ok(site), Some(release)) => set(site, pack(release)),
        _ => set(u32::MAX, 0),
    }
}
`;

/** The source of one file with its gates numbered and the functions holding them no longer const. */
function rewritten(text, sites) {
  const lines = text.split("\n");
  const byLine = new Map();
  for (const site of sites) byLine.set(site.line - 1, [...(byLine.get(site.line - 1) ?? []), site]);
  for (const [index, held] of byLine) {
    let next = 0;
    lines[index] = lines[index].replace(GATE, (whole, receiver) => `crate::gate_probe::gate(&${receiver}, ${held[next++].site}, ${whole})`);
    for (let at = index; at >= 0; at -= 1) {
      if (/^\s*(?:pub(?:\([a-z]+\))? )?const fn /.test(lines[at])) {
        lines[at] = lines[at].replace("const fn ", "fn ");
        break;
      }
      if (/^\s*(?:pub(?:\([a-z]+\))? )?fn /.test(lines[at])) break;
    }
  }
  return lines.join("\n");
}

function prepare(target) {
  const native = path.join(target, "native");
  fs.mkdirSync(native, { recursive: true });
  for (const entry of ["Cargo.toml", "Cargo.lock", "build.rs", "data", "fixtures", "src", "tests"]) {
    const from = path.join(root, "native", entry);
    if (fs.existsSync(from)) fs.cpSync(from, path.join(native, entry), { recursive: true });
  }
  const sites = gateSites();
  const copied = path.join(native, "src");
  for (const file of new Set(sites.map((site) => site.file))) {
    const at = path.join(copied, file);
    const text = fs.readFileSync(at, "utf8").replace(/\r\n/g, "\n");
    fs.writeFileSync(at, rewritten(text, sites.filter((site) => site.file === file)));
  }
  fs.writeFileSync(path.join(copied, "gate_probe.rs"), PROBE(sites.length));
  // the minecart's scene gates through a helper of its own
  fs.appendFileSync(path.join(copied, "minecart.rs"), `
impl crate::gate_probe::Released for Scene<'_> {
    fn released(&self) -> crate::version::MinecraftVersion {
        self.release()
    }
}
`);
  const lib = path.join(copied, "lib.rs");
  fs.writeFileSync(lib, `pub mod gate_probe;\n${fs.readFileSync(lib, "utf8")}`);
  fs.writeFileSync(path.join(target, "sites.json"), `${JSON.stringify(sites, null, 1)}\n`);
  console.log(`${sites.length} sites in ${target}`);
}

/** The Rust tests against each mutant: unit.jsonl in `target`, one line each, and what is there already is not done again. */
async function unit(target, binary, jobs = "3") {
  const { spawn, spawnSync } = require("node:child_process");
  const sites = JSON.parse(fs.readFileSync(path.join(target, "sites.json"), "utf8"));
  const cwd = path.join(target, "native");
  const hitsFile = path.join(target, "unit-hits.tsv");
  if (!fs.existsSync(hitsFile)) {
    const started = Date.now();
    const run = spawnSync(binary, [], { cwd, env: { ...process.env, GATE_HITS: hitsFile }, encoding: "utf8", maxBuffer: 1 << 28 });
    console.log(`baseline: ${run.stdout.trim().split("\n").at(-1)} in ${Math.round((Date.now() - started) / 1000)}s`);
    if (run.status !== 0) throw new Error(run.stdout.slice(-2000));
  }
  const reach = new Map();
  for (const line of fs.readFileSync(hitsFile, "utf8").split("\n")) {
    const [site, release, test] = line.split("\t");
    if (!test || test === "main" || test === "?") continue;
    const key = `${site}:${release}`;
    if (!reach.has(key)) reach.set(key, new Set());
    reach.get(key).add(test);
  }
  const out = path.join(target, "unit.jsonl");
  const done = new Set(fs.existsSync(out) ? fs.readFileSync(out, "utf8").split("\n").filter(Boolean).map((line) => { const entry = JSON.parse(line); return `${entry.site}:${entry.release}`; }) : []);
  const queue = [];
  for (const site of sites) {
    for (const release of new Set([site.firstFrom, site.lastBefore])) {
      if (release && !done.has(`${site.site}:${release}`)) queue.push({ site: site.site, release, tests: [...(reach.get(`${site.site}:${release}`) ?? [])] });
    }
  }
  console.log(`${queue.length} mutants`);
  const chunks = (list, size) => Array.from({ length: Math.ceil(list.length / size) }, (_, at) => list.slice(at * size, (at + 1) * size));
  const once = (mutant, names) => new Promise((resolve) => {
    const child = spawn(binary, ["--exact", ...names], { cwd, env: { ...process.env, GATE_MUTANT: `${mutant.site}:${mutant.release}` }, stdio: ["ignore", "pipe", "ignore"] });
    let text = "";
    child.stdout.on("data", (data) => { text += data; });
    const timer = setTimeout(() => { child.kill(); resolve({ hung: true }); }, 180000);
    child.on("close", (status) => {
      clearTimeout(timer);
      const failed = /^test (\S+) \.\.\. FAILED/m.exec(text)?.[1] ?? /^failures:\s*\n\s*\n?\s*(\S+)/m.exec(text)?.[1];
      resolve(status === 0 ? {} : { failed: failed ?? `exit ${status}` });
    });
  });
  const worker = async () => {
    for (;;) {
      const mutant = queue.shift();
      if (!mutant) return;
      let killedBy;
      for (const names of chunks(mutant.tests, 120)) {
        const result = await once(mutant, names);
        if (result.hung) killedBy = "(hung)";
        else if (result.failed) killedBy = result.failed;
        if (killedBy) break;
      }
      fs.appendFileSync(out, `${JSON.stringify({ site: mutant.site, release: mutant.release, tests: mutant.tests.length, killedBy })}\n`);
    }
  };
  await Promise.all(Array.from({ length: Number(jobs) }, worker));
}
/** The mutants no Rust test noticed, against the JavaScript tests: js.jsonl in `target`. */
async function js(target, jobs = "3") {
  const { spawn, spawnSync } = require("node:child_process");
  const addon = path.join(target, "out", "index.win32-x64-msvc.node");
  const environment = { ...process.env, NAPI_RS_NATIVE_LIBRARY_PATH: addon };
  const files = fs.readdirSync(path.join(root, "test")).filter((name) => name.endsWith(".test.cjs")).sort();
  const hitsDirectory = path.join(target, "js-hits");
  fs.mkdirSync(hitsDirectory, { recursive: true });
  const reach = new Map();
  for (const file of files) {
    const hits = path.join(hitsDirectory, `${file}.tsv`);
    if (!fs.existsSync(hits)) {
      fs.writeFileSync(hits, "");
      const started = Date.now();
      const run = spawnSync(process.execPath, ["--test", `test/${file}`], { cwd: root, env: { ...environment, GATE_HITS: hits }, stdio: "ignore", timeout: 300000 });
      console.log(`${file}: exit ${run.status} in ${Math.round((Date.now() - started) / 1000)}s`);
      if (run.status !== 0) fs.writeFileSync(hits, "");
    }
    for (const line of fs.readFileSync(hits, "utf8").split("\n")) {
      const [site, release] = line.split("\t");
      if (!release) continue;
      const key = `${site}:${release}`;
      if (!reach.has(key)) reach.set(key, new Set());
      reach.get(key).add(file);
    }
  }
  const out = path.join(target, "js.jsonl");
  const done = new Set(fs.existsSync(out) ? fs.readFileSync(out, "utf8").split("\n").filter(Boolean).map((line) => { const entry = JSON.parse(line); return `${entry.site}:${entry.release}`; }) : []);
  const queue = fs.readFileSync(path.join(target, "unit.jsonl"), "utf8").split("\n").filter(Boolean).map((line) => JSON.parse(line))
    .filter((entry) => !entry.killedBy && !done.has(`${entry.site}:${entry.release}`) && reach.has(`${entry.site}:${entry.release}`));
  console.log(`${queue.length} mutants`);
  const once = (mutant, file) => new Promise((resolve) => {
    const child = spawn(process.execPath, ["--test", `test/${file}`], { cwd: root, env: { ...environment, GATE_MUTANT: `${mutant.site}:${mutant.release}` }, stdio: "ignore" });
    const timer = setTimeout(() => { child.kill(); resolve(true); }, 300000);
    child.on("close", (status) => { clearTimeout(timer); resolve(status !== 0); });
  });
  const worker = async () => {
    for (;;) {
      const mutant = queue.shift();
      if (!mutant) return;
      let killedBy;
      for (const file of reach.get(`${mutant.site}:${mutant.release}`)) {
        if (await once(mutant, file)) { killedBy = file; break; }
      }
      fs.appendFileSync(out, `${JSON.stringify({ site: mutant.site, release: mutant.release, files: reach.get(`${mutant.site}:${mutant.release}`).size, killedBy })}\n`);
    }
  };
  await Promise.all(Array.from({ length: Number(jobs) }, worker));
}

/** Chosen mutants again, against the tests a filter names, after fixtures were added: one line each to `out`, as unit.jsonl's.
 *  The binary is the test build of a fresh `prepare` of the tree that holds the fixtures, whose sites must be the sweep's. */
async function recheck(target, binary, out, filter, siteList) {
  const { spawnSync } = require("node:child_process");
  const sites = JSON.parse(fs.readFileSync(path.join(target, "sites.json"), "utf8"));
  const cwd = path.join(target, "native");
  for (const number of siteList) {
    const site = sites[number];
    if (!site) throw new Error(`no site ${number} in ${target}`);
    for (const release of new Set([site.lastBefore, site.firstFrom])) {
      if (!release) continue;
      const run = spawnSync(binary, [filter], { cwd, env: { ...process.env, GATE_MUTANT: `${site.site}:${release}` }, encoding: "utf8", maxBuffer: 1 << 28, timeout: 300000 });
      const summary = /test result: \w+\. (\d+) passed; (\d+) failed/.exec(run.stdout ?? "");
      const tests = summary ? Number(summary[1]) + Number(summary[2]) : 0;
      const failed = /^test (\S+) \.\.\. FAILED/m.exec(run.stdout ?? "")?.[1];
      const killedBy = run.status === 0 ? undefined : (failed ?? (run.error ? "(hung)" : `exit ${run.status}`));
      fs.appendFileSync(out, `${JSON.stringify({ site: site.site, release, tests, killedBy })}\n`);
      console.log(`${site.site} ${site.file}#${site.function}@${site.boundary} on ${release}: ${killedBy ?? "not caught"} (${tests} tests)`);
    }
  }
}

if (require.main === module) {
  const [command, target] = process.argv.slice(2);
  if (command === "prepare" && target) prepare(path.resolve(target));
  else if (command === "unit" && target) unit(path.resolve(target), process.argv[4], process.argv[5]).then(() => process.exit(0));
  else if (command === "js" && target) js(path.resolve(target), process.argv[4]).then(() => process.exit(0));
  else if (command === "recheck" && target) recheck(path.resolve(target), process.argv[4], path.resolve(process.argv[5]), process.argv[6], process.argv.slice(7).flatMap((list) => list.split(",")).map(Number)).then(() => process.exit(0));
  else if (command === "sites") for (const site of gateSites()) console.log(JSON.stringify(site));
  else {
    console.error("usage: gate-mutants.cjs prepare <dir> | unit <dir> <binary> <jobs> | js <dir> <jobs> | recheck <dir> <binary> <out> <filter> <sites> | sites");
    process.exit(1);
  }
}

/** The gates of native/src as a commit holds it, which is what a sweep of that commit flipped: the pin of generated/gate-mutation.json. */
function gateSitesAt(commit) {
  const childProcess = require("node:child_process");
  const os = require("node:os");
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "mc-gate-sites-"));
  try {
    childProcess.execFileSync("git", ["-C", root, "archive", "--format=tar", "-o", path.join(directory, "src.tar"), commit, "native/src"], { stdio: ["ignore", "ignore", "pipe"] });
    childProcess.execFileSync("tar", ["-xf", "src.tar"], { cwd: directory, stdio: "ignore" });
    return gateSites(canonicalReleases(), path.join(directory, "native", "src"));
  } finally {
    fs.rmSync(directory, { recursive: true, force: true });
  }
}

/** What a sweep's gates differ by from those of the commit it says it swept, one line each: empty when they are the same. */
function sweepProblems(sites, commit) {
  const key = (site) => `${site.file}#${site.function}@${site.boundary}`;
  const count = (list) => list.reduce((counts, item) => counts.set(item, (counts.get(item) ?? 0) + 1), new Map());
  const expected = count(gateSitesAt(commit).map(key));
  const swept = count(sites.map(key));
  const missing = [...expected].filter(([item, n]) => (swept.get(item) ?? 0) < n).map(([item]) => item);
  const extra = [...swept].filter(([item, n]) => (expected.get(item) ?? 0) < n).map(([item]) => item);
  return [...missing.map((item) => `${item}: a gate of ${commit} the sweep has no entry for`), ...extra.map((item) => `${item}: swept, and no gate of ${commit}`)];
}

module.exports = { gateSites, gateSitesAt, sweepProblems, prepare };
