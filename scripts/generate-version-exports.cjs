"use strict";

// Writes src/versions.ts and src/mineflayer/versions.ts from the canonical release inventory
// (scripts/release-inventory.cjs). The native registry stays hand-written, one concrete module per
// release: finding a release in a list must not manufacture an engine, so a release the inventory
// names and native does not is an inventory problem, not something generated around. With --check
// nothing is written and a difference fails (line endings aside).

const fs = require("node:fs");
const path = require("node:path");
const { canonicalReleases } = require("./release-inventory.cjs");

const root = path.resolve(__dirname, "..");
const versionsPath = path.join(root, "src", "versions.ts");
const enginesPath = path.join(root, "src", "mineflayer", "versions.ts");

function versionsSource(versions) {
  return `// Generated by scripts/generate-version-exports.cjs from the release inventory: do not edit. The releases the engine has
// a module for; scripts/release-inventory.cjs holds native/src/versioned/mod.rs to the same inventory, name by name.
export const SUPPORTED_VERSIONS = [
${versions.map((version) => `    '${version}',`).join("\n")}
] as const;

/** A release the engine has a module for. */
export type SupportedVersion = (typeof SUPPORTED_VERSIONS)[number];

const SUPPORTED: ReadonlySet<string> = new Set(SUPPORTED_VERSIONS);

/** Whether the engine has a module for the release (what the binding's isSupportedVersion answers). */
export function isSupportedVersion(version: string): version is SupportedVersion {
    return SUPPORTED.has(version);
}
`;
}

function enginesSource(versions) {
  const className = (version) => `NativePhysics_${version.replaceAll(".", "_")}`;
  const classes = versions.map((version) => `/** The native engine of Minecraft ${version}. */
export class ${className(version)} extends VersionedNativePhysics<'${version}'> {
    static readonly version = '${version}';

    constructor(registry: PhysicsRegistry, options: VersionedNativePhysicsOptions = {}) {
        super('${version}', registry, options);
    }
}
`);
  return `// Generated by scripts/generate-version-exports.cjs from the release inventory: do not edit. One public engine class per
// release the engine has a module for, and the registry that dispatches a release to its class. The registry's type
// makes the compiler refuse a release of SUPPORTED_VERSIONS without its class, a class under another release's key, and
// a key that is not a supported release.
import type { SupportedVersion } from '../versions';
import type { NativeEngineOptions, PhysicsRegistry } from './base';
import { NativePhysics } from './player';
import { resolveRegistryRelease } from './registry-release';

/** The options of a release's own engine class: the release is the class's. */
export type VersionedNativePhysicsOptions = Omit<NativeEngineOptions, 'version'>;

/** The engine class of one release. */
export interface VersionedNativePhysicsClass<V extends SupportedVersion = SupportedVersion> {
    readonly version: V;
    new (registry: PhysicsRegistry, options?: VersionedNativePhysicsOptions): NativePhysics & { readonly version: V };
}

/** What every release's engine class is: NativePhysics running that release. */
export abstract class VersionedNativePhysics<V extends SupportedVersion> extends NativePhysics {
    declare readonly version: V;

    protected constructor(version: V, registry: PhysicsRegistry, options: VersionedNativePhysicsOptions = {}) {
        resolveRegistryRelease(registry, version);
        super(registry, { binding: options.binding, requireParity: options.requireParity, version });
    }
}

${classes.join("\n")}
/** Each supported release's engine class. */
export const NATIVE_PHYSICS_ENGINES = {
${versions.map((version) => `    '${version}': ${className(version)},`).join("\n")}
} as const satisfies { readonly [V in SupportedVersion]: VersionedNativePhysicsClass<V> };

/**
 * The engine of a release (\`options.version\`, else the registry's): an instance of that release's class. A release
 * without one or a mismatched registry is refused here, before any binding is loaded.
 */
export function createNativePhysics(registry: PhysicsRegistry, options: NativeEngineOptions = {}): NativePhysics {
    const version = resolveRegistryRelease(registry, options.version);
    const Engine: VersionedNativePhysicsClass = NATIVE_PHYSICS_ENGINES[version];
    return new Engine(registry, { binding: options.binding, requireParity: options.requireParity });
}
`;
}

/** Each generated file and its text for a release list. */
const generatedFiles = (versions = canonicalReleases()) => [[versionsPath, versionsSource(versions)], [enginesPath, enginesSource(versions)]];

const normalized = (text) => text.replaceAll("\r\n", "\n");

module.exports = { generatedFiles, normalized };

if (require.main === module) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [file, text] of generatedFiles()) {
    if (!check) fs.writeFileSync(file, text);
    else if (normalized(fs.readFileSync(file, "utf8")) !== text) {
      stale = true;
      console.error(`${path.relative(root, file)} is not what generate-version-exports.cjs writes`);
    }
  }
  if (stale) process.exit(1);
}
