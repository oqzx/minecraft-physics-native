"use strict";

// Writes src/mineflayer/vehicle-versions.ts: one boat and one ridden mob engine class per registered release, as
// src/mineflayer/versions.ts has for the player. test/vehicle-engines.test.cjs keeps the file equal to this output.

const fs = require("node:fs");
const path = require("node:path");
const { canonicalReleases } = require("./release-inventory.cjs");

const outputPath = path.resolve(__dirname, "..", "src", "mineflayer", "vehicle-versions.ts");

const families = [
  { base: "NativeBoatPhysics", map: "NATIVE_BOAT_ENGINES", factory: "createNativeBoatPhysics", what: "boat" },
  { base: "NativeRiddenMobPhysics", map: "NATIVE_RIDDEN_MOB_ENGINES", factory: "createNativeRiddenMobPhysics", what: "ridden mob" },
];

function familySource(family, versions) {
  const { base, map, factory, what } = family;
  const className = (version) => `${base}_${version.replaceAll(".", "_")}`;
  const classes = versions.map((version) => `/** The ${what} engine of Minecraft ${version}. */
export class ${className(version)} extends Versioned${base}<'${version}'> {
    static readonly version = '${version}';

    constructor(registry: PhysicsRegistry, options: VersionedVehicleOptions = {}) {
        super('${version}', registry, options);
    }
}
`);
  return `/** The ${what} engine class of one release. */
export interface Versioned${base}Class<V extends SupportedVersion = SupportedVersion> {
    readonly version: V;
    new (registry: PhysicsRegistry, options?: VersionedVehicleOptions): ${base} & { readonly version: V };
}

/** What every release's ${what} engine class is: ${base} running that release. */
export abstract class Versioned${base}<V extends SupportedVersion> extends ${base} {
    declare readonly version: V;

    protected constructor(version: V, registry: PhysicsRegistry, options: VersionedVehicleOptions = {}) {
        resolveRegistryRelease(registry, version);
        super(registry, { binding: options.binding, requireParity: options.requireParity, version });
    }
}

${classes.join("\n")}
/** Each supported release's ${what} engine class. */
export const ${map} = {
${versions.map((version) => `    '${version}': ${className(version)},`).join("\n")}
} as const satisfies { readonly [V in SupportedVersion]: Versioned${base}Class<V> };

/** The ${what} engine of a release (\`options.version\`, else the registry's), an instance of that release's class. */
export function ${factory}(registry: PhysicsRegistry, options: NativeEngineOptions = {}): ${base} {
    const version = resolveRegistryRelease(registry, options.version);
    const Engine: Versioned${base}Class = ${map}[version];
    return new Engine(registry, { binding: options.binding, requireParity: options.requireParity });
}
`;
}

function vehicleEnginesSource(versions = canonicalReleases()) {
  return `// Generated by scripts/generate-vehicle-engines.cjs from the release inventory: do not edit. Each release's own boat and
// ridden mob engine class, which binds it to one exact release as ./versions does the player's. The registries' types
// make the compiler refuse a supported release without its class.
import type { SupportedVersion } from '../versions';
import type { NativeEngineOptions, PhysicsRegistry } from './base';
import { resolveRegistryRelease } from './registry-release';
import { NativeBoatPhysics, NativeRiddenMobPhysics } from './vehicles';

/** The options of a release's own vehicle engine class: the release is the class's. */
export type VersionedVehicleOptions = Omit<NativeEngineOptions, 'version'>;

${families.map((family) => familySource(family, versions)).join("\n")}`;
}

module.exports = { vehicleEnginesSource, outputPath };

if (require.main === module) {
  fs.writeFileSync(outputPath, vehicleEnginesSource());
}
